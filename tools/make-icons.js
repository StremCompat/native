'use strict';

// Draws the interface's icons (the SVGs of the web interface, so both look the same) into one
// picture, assets/icons.png, white on transparent in cells of CELL pixels, and writes
// src/icons.h with their order. A headless Edge or Chrome draws them; no window opens.
//
// Usage: node tools/make-icons.js <public-repo folder> [browser executable]

var childProcess = require('child_process');
var fs = require('fs');
var os = require('os');
var path = require('path');

var CELL = 64;
var COLUMNS = 8;
var here = path.resolve(__dirname, '..');
var repo = path.resolve(process.argv[2] || path.join(here, '..', 'LG', 'public-repo'));
var browser =
  process.argv[3] ||
  ['C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', 'C:/Program Files/Google/Chrome/Application/chrome.exe']
    .filter(function (p) {
      return fs.existsSync(p);
    })[0];

/* the navigation icons are outlines (nav.css); the others are filled shapes (artwork.js) */
function navIcons() {
  var html = fs.readFileSync(path.join(repo, 'src', 'ui', 'index.html'), 'utf8');
  var names = { Search: 'search', Home: 'home', Disc: 'discover', Lib: 'library', Addons: 'addons', Set: 'settings', Update: 'update', Exit: 'leave' };
  var out = [];
  var re = /id="chip([A-Za-z]+)"><svg viewBox="0 0 24 24">([\s\S]*?)<\/svg>/g,
    m;
  while ((m = re.exec(html)))
    if (names[m[1]]) out.push({ name: names[m[1]], body: m[2], outline: true });
  return out;
}

function shapeIcons() {
  var source = fs.readFileSync(path.join(repo, 'src', 'ui', 'data', 'artwork.js'), 'utf8');
  var block = /var ICON = \{([\s\S]*?)\n\};/.exec(source)[1];
  var out = [];
  var re = /^\s*([a-z]+):\s*'<svg viewBox="0 0 24 24">([\s\S]*?)<\/svg>'/gm,
    m;
  while ((m = re.exec(block))) out.push({ name: m[1], body: m[2], outline: false });
  return out;
}

/* the player's buttons (filled shapes), from the web player's page */
function playerIcons() {
  var html = fs.readFileSync(path.join(repo, 'service', 'player', 'player-body.html'), 'utf8');
  var names = { media: 'subtitles', ep: 'episodes', src: 'sources', rw: 'rewind', ff: 'forward', set: 'gear' };
  var out = [];
  var re = /id="b_([a-z]+)"><svg viewBox="0 0 24 24"[^>]*>([\s\S]*?)<\/svg>/g,
    m;
  while ((m = re.exec(html)))
    if (names[m[1]]) out.push({ name: names[m[1]], body: m[2], outline: false });
  return out;
}

var icons = navIcons().concat(shapeIcons(), playerIcons());
var rows = Math.ceil(icons.length / COLUMNS);
var width = CELL * COLUMNS,
  height = CELL * rows;

var cells = icons
  .map(function (icon, i) {
    var x = (i % COLUMNS) * CELL,
      y = Math.floor(i / COLUMNS) * CELL;
    var style = icon.outline
      ? 'fill="none" stroke="#fff" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"'
      : 'fill="#fff"';
    return (
      '<svg style="position:absolute;left:' + x + 'px;top:' + y + 'px" width="' + CELL + '" height="' + CELL +
      '" viewBox="0 0 24 24" ' + style + '>' + icon.body + '</svg>'
    );
  })
  .join('\n');
var page =
  '<!doctype html><html><body style="margin:0;background:transparent;width:' + width + 'px;height:' + height +
  'px;overflow:hidden">' + cells + '</body></html>';

var dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sc-icons-'));
var pageFile = path.join(dir, 'icons.html'),
  shot = path.join(dir, 'icons.png');
fs.writeFileSync(pageFile, page);
childProcess.execFileSync(browser, [
  '--headless=new',
  '--disable-gpu',
  '--hide-scrollbars',
  '--force-device-scale-factor=1',
  '--default-background-color=00000000',
  '--window-size=' + width + ',' + height,
  '--screenshot=' + shot,
  'file:///' + pageFile.replace(/\\/g, '/')
]);
fs.copyFileSync(shot, path.join(here, 'assets', 'icons.png'));

var header =
  '/* Generated by tools/make-icons.js: the order of the icons in assets/icons.png. */\n' +
  '#ifndef SC_ICONS_H\n#define SC_ICONS_H\n\n' +
  '#define ICON_CELL ' + CELL + '\n#define ICON_COLUMNS ' + COLUMNS + '\n\n' +
  'typedef enum {\n' +
  icons
    .map(function (icon) {
      return '  ICON_' + icon.name.toUpperCase() + ',\n';
    })
    .join('') +
  '  ICON_COUNT\n} icon_id;\n\n#endif\n';
fs.writeFileSync(path.join(here, 'src', 'icons.h'), header);
console.log('icons: ' + icons.length + ' (' + width + 'x' + height + ')');
